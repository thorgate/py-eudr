#!/usr/bin/env python
"""Generate ``py_eudr/types/<version>.pyi`` type stubs from the vendored schemas.

The stubs describe the zeep types of the EUDR DDS, SD and Verify services: one class
per complex type of an EUDR namespace (attributes and a keyword-only ``__init__``),
``Literal`` aliases for enumerations, plain aliases for other simple types, and the
``DdsTypes``/``SdTypes``/``VerifyTypes``/``V3Types`` (``V4Types``) namespaces that
describe ``client.types``.

Runtime objects stay dynamic zeep objects; the stubs are only seen by type checkers
and IDEs. Usage::

    python scripts/generate_stubs.py           # write py_eudr/types/v3.pyi and v4.pyi
    python scripts/generate_stubs.py --check   # exit 1 if the committed stubs are stale
"""

import argparse
import os
import re
import sys
import textwrap
import typing as t

from lxml import etree
from zeep.xsd import ComplexType
from zeep.xsd.elements import Element
from zeep.xsd.types import builtins as xsd_builtins

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from py_eudr.base import ServiceClient  # noqa: E402

TYPES_DIR = os.path.join(ROOT, "py_eudr", "types")
SCHEMAS_DIR = os.path.join(ROOT, "py_eudr", "schemas")

EUDR_NAMESPACE = "http://ec.europa.eu/tracesnt/certificate/eudr/"
XS = "{http://www.w3.org/2001/XMLSchema}"

VERSIONS = ("v3", "v4")

# (attribute name on client.types, namespace class, service name without version)
SERVICES = (
    ("dds", "DdsTypes", "EUDRDueDiligenceStatementService"),
    ("sd", "SdTypes", "EUDRSimplifiedDeclarationService"),
    ("verify", "VerifyTypes", "EUDRVerifyDeclarationService"),
)

# XSD builtin -> (python type of values zeep returns, extra types zeep accepts on input)
BUILTINS: t.Dict[str, t.Tuple[str, str]] = {
    "string": ("str", ""),
    "normalizedString": ("str", ""),
    "token": ("str", ""),
    "anyURI": ("str", ""),
    "language": ("str", ""),
    "NMTOKEN": ("str", ""),
    "boolean": ("bool", ""),
    "integer": ("int", ""),
    "int": ("int", ""),
    "long": ("int", ""),
    "short": ("int", ""),
    "byte": ("int", ""),
    "nonNegativeInteger": ("int", ""),
    "positiveInteger": ("int", ""),
    "unsignedInt": ("int", ""),
    "unsignedLong": ("int", ""),
    "decimal": ("Decimal", "float | int | str"),
    "double": ("float", ""),
    "float": ("float", ""),
    "dateTime": ("datetime", "str"),
    "date": ("date", "str"),
    "time": ("time", "str"),
    "base64Binary": ("bytes", "str"),
}

HEADER = """\
# Generated by scripts/generate_stubs.py from the vendored EUDR {version} schemas.
# Do not edit by hand; run `python scripts/generate_stubs.py` after refreshing the schemas.
#
# Runtime objects are zeep objects; these classes only describe them for type checkers.
# Wherever a complex type is expected, zeep also accepts a plain dict (`_Dict`), which
# is not checked.

{imports}

_Dict: TypeAlias = Mapping[str, Any]
"""


def builtin_name(xsd_type: t.Any) -> t.Optional[str]:
    """Return the local name of the XSD builtin a zeep simple type derives from."""
    for cls in type(xsd_type).__mro__:
        if cls.__module__ == xsd_builtins.__name__ and hasattr(cls, "_default_qname"):
            local = cls._default_qname.localname
            if local in BUILTINS:
                return local
    return None


def collect_enumerations(directory: str) -> t.Dict[t.Tuple[str, str], t.List[str]]:
    """Enumeration facets of named simple types, keyed by (namespace, name).

    zeep does not expose facets, so they are read from the XSD files directly.
    """
    enums: t.Dict[t.Tuple[str, str], t.List[str]] = {}
    for file_name in sorted(os.listdir(directory)):
        if not file_name.endswith(".xsd"):
            continue
        root = etree.parse(os.path.join(directory, file_name)).getroot()
        namespace = root.get("targetNamespace", "")
        for simple_type in root.iter(XS + "simpleType"):
            name = simple_type.get("name")
            values = [e.get("value") for e in simple_type.iter(XS + "enumeration")]
            if name and values:
                enums[(namespace, name)] = values
    return enums


def documentation(directory: str) -> t.Dict[t.Tuple[str, str], str]:
    """First documentation paragraph of named complex types, keyed by (namespace, name)."""
    docs: t.Dict[t.Tuple[str, str], str] = {}
    for file_name in sorted(os.listdir(directory)):
        if not file_name.endswith(".xsd"):
            continue
        root = etree.parse(os.path.join(directory, file_name)).getroot()
        namespace = root.get("targetNamespace", "")
        for node in root.findall(XS + "complexType"):
            text = node.findtext(f"{XS}annotation/{XS}documentation")
            if node.get("name") and text and text.strip():
                docs[(namespace, node.get("name"))] = " ".join(text.split())
    return docs


class StubBuilder:
    def __init__(self, version: str):
        self.version = version
        self.clients = {
            key: ServiceClient(f"{service}{version.upper()}")
            for key, _, service in SERVICES
        }
        self.enums: t.Dict[t.Tuple[str, str], t.List[str]] = {}
        self.docs: t.Dict[t.Tuple[str, str], str] = {}
        for _, _, service in SERVICES:
            directory = os.path.join(
                SCHEMAS_DIR, version, f"{service}{version.upper()}"
            )
            self.enums.update(collect_enumerations(directory))
            self.docs.update(documentation(directory))

        # name -> zeep type, for every global type of an EUDR namespace
        self.complex_types: t.Dict[str, t.Any] = {}
        self.simple_types: t.Dict[str, t.Any] = {}
        self.service_types: t.Dict[str, t.List[str]] = {}
        for key, client in self.clients.items():
            names = set()
            for xsd_type in client.wsdl.types.types:
                if not self.is_eudr(xsd_type):
                    continue
                name = xsd_type.qname.localname
                target = (
                    self.complex_types
                    if isinstance(xsd_type, ComplexType)
                    else self.simple_types
                )
                other = target.get(name)
                if other is not None and other.qname != xsd_type.qname:
                    raise RuntimeError(
                        f"Type name collision: {other.qname} {xsd_type.qname}"
                    )
                target.setdefault(name, xsd_type)
                if isinstance(xsd_type, ComplexType):
                    names.add(name)
            self.service_types[key] = sorted(names)

    @staticmethod
    def is_eudr(xsd_type: t.Any) -> bool:
        qname = getattr(xsd_type, "qname", None)
        return qname is not None and qname.namespace.startswith(EUDR_NAMESPACE)

    def is_global(self, xsd_type: t.Any) -> bool:
        if not self.is_eudr(xsd_type):
            return False
        name = xsd_type.qname.localname
        registry = (
            self.complex_types
            if isinstance(xsd_type, ComplexType)
            else self.simple_types
        )
        return registry.get(name) is xsd_type or (
            name in registry and registry[name].qname == xsd_type.qname
        )

    def annotation(self, xsd_type: t.Any, *, param: bool) -> str:
        if isinstance(xsd_type, ComplexType):
            if self.is_global(xsd_type):
                name = xsd_type.qname.localname
                return f"{name} | _Dict" if param else name
            return "_Dict" if param else "Any"
        builtin = builtin_name(xsd_type)
        if self.is_global(xsd_type):
            name = xsd_type.qname.localname
        elif builtin is not None:
            name = BUILTINS[builtin][0]
        else:
            return "Any"
        extra = BUILTINS[builtin][1] if builtin is not None else ""
        if param and extra and (xsd_type.qname.namespace, name) not in self.enums:
            return f"{name} | {extra}"
        return name

    def fields(self, xsd_type: ComplexType) -> t.List[t.Tuple[str, str, str, bool]]:
        """(name, attribute annotation, parameter annotation, optional) per element."""
        result = []
        for _, particle in xsd_type.elements_nested:
            in_choice = type(particle).__name__ == "Choice"
            optional_group = getattr(particle, "min_occurs", 1) == 0
            if isinstance(particle, Element):
                elements = [(particle.name, particle)]
            else:
                elements = particle.elements
            for name, element in elements:
                if not isinstance(element, Element):
                    raise RuntimeError(
                        f"Unsupported particle {element!r} in {xsd_type.qname}"
                    )
                attr = self.annotation(element.type, param=False)
                param = self.annotation(element.type, param=True)
                max_occurs = element.max_occurs
                many = max_occurs == "unbounded" or int(max_occurs) > 1
                optional = in_choice or optional_group or element.min_occurs == 0
                if many:
                    attr, param = f"list[{attr}]", f"Sequence[{param}]"
                    if optional:
                        param = f"{param} | None"
                    # zeep returns [] for an absent list in a sequence, but None when
                    # the enclosing choice/group is absent.
                    if in_choice or optional_group:
                        attr = f"{attr} | None"
                elif optional:
                    attr, param = f"{attr} | None", f"{param} | None"
                result.append((name, attr, param, optional))
        return result

    def render_simple(self, name: str) -> str:
        xsd_type = self.simple_types[name]
        values = self.enums.get((xsd_type.qname.namespace, name))
        if values:
            literal = ", ".join(f'"{v}"' for v in values)
            line = f"{name}: TypeAlias = Literal[{literal}]"
            if len(line) > 88:
                items = "".join(f'    "{v}",\n' for v in values)
                line = f"{name}: TypeAlias = Literal[\n{items}]"
            return line
        builtin = builtin_name(xsd_type)
        return f"{name}: TypeAlias = {BUILTINS[builtin][0] if builtin else 'Any'}"

    def render_complex(self, name: str) -> str:
        xsd_type = self.complex_types[name]
        lines = [f"class {name}:"]
        doc = self.docs.get((xsd_type.qname.namespace, name))
        if doc:
            doc = doc.replace("\\", "\\\\").replace('"""', "'''")
            wrapped = textwrap.wrap(doc, width=84)
            if len(wrapped) == 1 and len(wrapped[0]) <= 78:
                lines.append(f'    """{wrapped[0]}"""')
            else:
                lines.append('    """')
                lines += [f"    {line}" for line in wrapped]
                lines.append('    """')
            lines.append("")
        fields = self.fields(xsd_type)
        for field, attr, _, _ in fields:
            lines.append(f"    {field}: {attr}")
        if fields:
            lines.append("    def __init__(")
            lines.append("        self,")
            lines.append("        *,")
            for field, _, param, optional in fields:
                lines.append(
                    f"        {field}: {param}{' = None' if optional else ''},"
                )
            lines.append("    ) -> None: ...")
        else:
            lines.append("    def __init__(self) -> None: ...")
        return "\n".join(lines)

    def section(self, namespace: str) -> t.Tuple[t.List[str], t.List[str]]:
        simple = sorted(
            n for n, x in self.simple_types.items() if x.qname.namespace == namespace
        )
        complex_ = sorted(
            n for n, x in self.complex_types.items() if x.qname.namespace == namespace
        )
        return simple, complex_

    def render(self) -> str:
        namespaces = sorted(
            {x.qname.namespace for x in self.complex_types.values()}
            | {x.qname.namespace for x in self.simple_types.values()},
            key=lambda ns: (not ns.split("/")[-2] == "common", ns),
        )
        out = []
        for namespace in namespaces:
            simple, complex_ = self.section(namespace)
            out.append(f"# {'=' * 76}\n# {namespace}\n# {'=' * 76}\n")
            if simple:
                out.append("\n".join(self.render_simple(n) for n in simple) + "\n")
            for name in complex_:
                out.append(self.render_complex(name) + "\n")

        out.append(f"# {'=' * 76}\n# Namespaces of client.types\n# {'=' * 76}\n")
        for key, class_name, _ in SERVICES:
            lines = [f"class {class_name}:"]
            lines += [f"    {n}: type[{n}]" for n in self.service_types[key]]
            out.append("\n".join(lines) + "\n")
        lines = [f"class {self.version.upper()}Types:"]
        lines += [f"    {key}: {class_name}" for key, class_name, _ in SERVICES]
        out.append("\n".join(lines))
        body = "\n\n".join(block.rstrip("\n") for block in out) + "\n"
        header = HEADER.format(version=self.version.upper(), imports=self.imports(body))
        return re.sub(r"\n{3,}", "\n\n\n", header + "\n" + body)

    @staticmethod
    def imports(body: str) -> str:
        def used(names: t.Sequence[str]) -> t.List[str]:
            return [n for n in names if re.search(rf"\b{n}\b", body)]

        lines = []
        dt = used(["date", "datetime", "time"])
        dt = [
            n for n in dt if re.search(rf"(:|\[|\|) {n}\b|\b{n}( \||\]|$)", body, re.M)
        ]
        if dt:
            lines.append(f"from datetime import {', '.join(dt)}")
        if used(["Decimal"]):
            lines.append("from decimal import Decimal")
        typing_names = ["Any", "Mapping"] + used(["Literal", "Sequence"])
        lines.append(f"from typing import {', '.join(sorted(typing_names))}")
        lines.append("")
        lines.append("from typing_extensions import TypeAlias")
        return "\n".join(lines)


def render(version: str) -> str:
    return StubBuilder(version).render()


def main(argv: t.Optional[t.Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if stubs are stale"
    )
    parser.add_argument("--target", default=TYPES_DIR)
    options = parser.parse_args(argv)
    stale = []
    for version in VERSIONS:
        path = os.path.join(options.target, f"{version}.pyi")
        content = render(version)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        if current == content:
            continue
        stale.append(path)
        if not options.check:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(content)
    for path in stale:
        print(("stale: " if options.check else "wrote: ") + os.path.relpath(path, ROOT))
    return 1 if options.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
